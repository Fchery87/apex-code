#!/usr/bin/env node
/**
 * Generate a consolidated third-party dependency license report.
 *
 * NOTICE (repo root) already promises this: "a consolidated dependency license
 * report is generated as part of the release process." No such report existed
 * until this script (roadmap Phase 9).
 *
 * Reads package.json's "license" field directly from every installed package
 * under the root node_modules -- no new dependency, since npm already installs
 * everything with that field present. Workspace packages (this monorepo's own
 * code, resolved via realpath into packages/) are excluded; this is a report of
 * what Apex Code depends on, not a report of Apex Code itself.
 *
 * Usage:
 *   node scripts/apex/generate-license-report.mjs [--out <path>] [--stdout]
 *
 * Default output: .artifacts/third-party-licenses.md (gitignored; a release
 * build artifact, not a committed file -- dependency sets change too often for
 * a static copy to stay the source of truth).
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const NODE_MODULES = join(REPO_ROOT, "node_modules");
const DEFAULT_OUT = join(REPO_ROOT, ".artifacts", "third-party-licenses.md");

function readPackageJson(dir) {
	const path = join(dir, "package.json");
	if (!existsSync(path)) return undefined;
	try {
		return JSON.parse(readFileSync(path, "utf-8"));
	} catch {
		return undefined;
	}
}

function formatLicense(pkg) {
	if (typeof pkg.license === "string") return pkg.license;
	if (pkg.license && typeof pkg.license === "object" && typeof pkg.license.type === "string") {
		return pkg.license.type;
	}
	if (Array.isArray(pkg.licenses) && pkg.licenses.length > 0) {
		return pkg.licenses.map((entry) => entry.type ?? String(entry)).join(" OR ");
	}
	return undefined;
}

/**
 * A workspace package's node_modules entry is a symlink npm points at this
 * monorepo's own packages/ directory, resolved relative to nodeModulesDir's
 * parent -- not the script's own location -- so a fixture node_modules with its
 * own packages/ directory is correctly excluded too, not just the real repo's.
 */
function isWorkspacePackage(dir, packagesRoot) {
	try {
		const real = realpathSync(dir);
		return real.startsWith(`${packagesRoot}/`) || real === packagesRoot;
	} catch {
		return false;
	}
}

/** One entry per installed package directory directly under node_modules (handles @scope/name). */
export function collectPackageDirs(nodeModulesDir) {
	if (!existsSync(nodeModulesDir)) return [];
	const dirs = [];
	for (const entry of readdirSync(nodeModulesDir, { withFileTypes: true })) {
		if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
		if (entry.name.startsWith(".")) continue;
		if (entry.name.startsWith("@")) {
			const scopeDir = join(nodeModulesDir, entry.name);
			for (const scoped of readdirSync(scopeDir, { withFileTypes: true })) {
				if (scoped.isDirectory() || scoped.isSymbolicLink()) {
					dirs.push(join(scopeDir, scoped.name));
				}
			}
			continue;
		}
		dirs.push(join(nodeModulesDir, entry.name));
	}
	return dirs;
}

export function collectLicenseEntries(nodeModulesDir) {
	const packagesRoot = join(dirname(nodeModulesDir), "packages");
	const entries = [];
	for (const dir of collectPackageDirs(nodeModulesDir)) {
		if (isWorkspacePackage(dir, packagesRoot)) continue;
		const pkg = readPackageJson(dir);
		if (!pkg || !pkg.name) continue;
		entries.push({
			name: pkg.name,
			version: pkg.version ?? "unknown",
			license: formatLicense(pkg) ?? "UNKNOWN",
		});
	}
	// De-duplicate by name+version (npm can hoist the same package under
	// multiple scopes/paths in edge cases); keep the first occurrence.
	const seen = new Set();
	const deduped = [];
	for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version))) {
		const key = `${entry.name}@${entry.version}`;
		if (seen.has(key)) continue;
		seen.add(key);
		deduped.push(entry);
	}
	return deduped;
}

export function formatReport(entries) {
	const lines = [
		"# Third-party dependency licenses",
		"",
		"Generated by `scripts/apex/generate-license-report.mjs` as part of the release",
		"process (see `NOTICE`). Excludes this monorepo's own workspace packages.",
		"",
		`${entries.length} packages.`,
		"",
		"| Package | Version | License |",
		"| --- | --- | --- |",
	];
	for (const entry of entries) {
		lines.push(`| ${entry.name} | ${entry.version} | ${entry.license} |`);
	}
	return `${lines.join("\n")}\n`;
}

function parseArgs(argv) {
	let out = DEFAULT_OUT;
	let stdout = false;
	let nodeModulesDir = NODE_MODULES;
	for (let i = 0; i < argv.length; i++) {
		if (argv[i] === "--out") out = resolve(argv[++i]);
		else if (argv[i] === "--stdout") stdout = true;
		else if (argv[i] === "--node-modules") nodeModulesDir = resolve(argv[++i]);
	}
	return { out, stdout, nodeModulesDir };
}

function main() {
	const { out, stdout, nodeModulesDir } = parseArgs(process.argv.slice(2));
	const entries = collectLicenseEntries(nodeModulesDir);
	const report = formatReport(entries);

	if (stdout) {
		process.stdout.write(report);
		return;
	}

	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(out, report);
	console.log(`Wrote ${entries.length}-package license report to ${out}`);
}

// Compares decoded filesystem paths, not raw URL strings: this repository's own
// path contains a space ("Coding Projects"), which file://${process.argv[1]}
// does not percent-encode, so it never equals import.meta.url even when this
// *is* the entrypoint. fileURLToPath decodes both sides consistently.
if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
	main();
}
